"""Uploads all models, their textures and effect images, then writes
src/shared/Config/Assets.luau with the new IDs.

Run the Blender scripts first so everything is in one folder:
    python blender/training_dummy.py blender/out
    python blender/rat.py blender/out
    python blender/props.py blender/out
    python blender/characters.py blender/out
    python blender/effects.py blender/out
Then:
    python tools/build_assets.py blender/out

Only files that changed since the last upload are uploaded again
(tracked in tools/asset_manifest.json).
"""

import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from upload_model import upload  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MANIFEST = os.path.join(ROOT, "tools", "asset_manifest.json")
ASSETS_LUAU = os.path.join(ROOT, "src", "shared", "Config", "Assets.luau")

MODELS = ["TrainingDummy", "Rat", "Barrel", "HayBale", "Crate", "Tent", "Campfire", "Sign", "DirtPad", "Stall",
          "QuestGiver", "BanditThug"]
IMAGES = ["FxSpark", "FxDust", "FxGlow", "FxRing", "FxTrail"]


def sha(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def upload_if_changed(manifest, key, path, display):
    digest = sha(path)
    entry = manifest.get(key)
    if entry and entry["sha"] == digest:
        return entry["id"]
    asset_id = upload(path, display, "Realm of Crowns asset")
    manifest[key] = {"sha": digest, "id": asset_id}
    with open(MANIFEST, "w") as f:
        json.dump(manifest, f, indent=2, sort_keys=True)
    print(f"uploaded {key}: {asset_id}")
    return asset_id


def main(folder):
    manifest = {}
    if os.path.exists(MANIFEST):
        with open(MANIFEST) as f:
            manifest = json.load(f)

    models, images = {}, {}
    for name in MODELS:
        model_id = upload_if_changed(manifest, name + ".fbx", os.path.join(folder, name + ".fbx"), f"RoC {name}")
        texture_id = upload_if_changed(manifest, name + ".png", os.path.join(folder, name + ".png"), f"RoC {name} texture")
        models[name] = (model_id, texture_id)
    for name in IMAGES:
        images[name] = upload_if_changed(manifest, name + ".png", os.path.join(folder, name + ".png"), f"RoC {name}")

    lines = [
        "-- Generated by tools/build_assets.py. Don't edit by hand; rebuild instead.",
        "-- Models: the uploaded mesh and its texture (uploaded as a Decal).",
        "-- Images: effect images (Decals). The server looks up the real image IDs",
        "-- from the Decals when it starts (see Services/AssetService).",
        "",
        "return {",
        "\tModels = {",
    ]
    for name, (model_id, texture_id) in models.items():
        lines.append(f"\t\t{name} = {{ Model = {model_id}, Texture = {texture_id} }},")
    lines += ["\t},", "\tImages = {"]
    for name, image_id in images.items():
        lines.append(f"\t\t{name} = {image_id},")
    lines += ["\t},", "}", ""]
    with open(ASSETS_LUAU, "w") as f:
        f.write("\n".join(lines))
    print("wrote", ASSETS_LUAU)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "blender", "out"))
